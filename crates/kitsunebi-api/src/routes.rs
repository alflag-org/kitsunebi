/// Store bytes in the active, actor-owned change session. The response is a
/// content reference only; plan payloads never carry file bytes.
async fn stage_content(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Path(id): Path<String>,
    headers: HeaderMap,
    body: Bytes,
) -> Result<Json<crate::dto::StagedContentDto>, ApiError> {
    validate_uuid_path(&id, "change_session_id")?;
    if headers.get_all(header::CONTENT_TYPE).iter().count() != 1
        || headers
            .get(header::CONTENT_TYPE)
            .and_then(|value| value.to_str().ok())
            .and_then(|value| value.split(';').next())
            .map(str::trim)
            != Some("application/octet-stream")
    {
        return Err(ApiError::InvalidRequest(
            "application/octet-stream content type is required",
        ));
    }
    if headers.get_all(header::CONTENT_LENGTH).iter().count() > 1 {
        return Err(ApiError::InvalidRequest("invalid content length"));
    }
    if let Some(length) = headers.get(header::CONTENT_LENGTH) {
        let length = length
            .to_str()
            .ok()
            .and_then(|value| value.parse::<u64>().ok())
            .ok_or(ApiError::InvalidRequest("invalid content length"))?;
        if length > state.security.upload_limit as u64 {
            return Err(ApiError::PayloadTooLarge);
        }
        if length != body.len() as u64 {
            return Err(ApiError::InvalidRequest(
                "content length does not match body",
            ));
        }
    }
    if body.len() > state.security.upload_limit {
        return Err(ApiError::PayloadTooLarge);
    }
    check_state_change(&state.security, &headers, &actor).await?;
    state
        .management
        .authorize(&actor, "change-sessions", Some(&id), Permission::ChangePlan)
        .await?;
    let if_match = required_header(&headers, "if-match", 256)?;
    let session_version = parse_session_version(if_match)?;
    let idempotency_key = required_header(&headers, "idempotency-key", 128)?;
    let classification =
        parse_staged_classification(required_header(&headers, "x-kitsunebi-classification", 64)?)?;
    let request_hash = crate::plan_hash(&body);
    state
        .management
        .stage_content(
            &actor,
            crate::ports::StageContentRequest {
                session_id: id,
                bytes: body.to_vec(),
                classification,
                session_version,
                idempotency_key: idempotency_key.to_owned(),
                request_hash,
            },
        )
        .await
        .map(Json)
}

/// Record a bounded out-of-band SFTP observation. This is an observation
/// attached to an active change session, not a realtime audit stream and not
/// a provider mutation.
async fn scan_sftp(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Extension(request_id): Extension<RequestId>,
    Path(endpoint_id): Path<String>,
    headers: HeaderMap,
    body: Result<Json<crate::dto::SftpScanPayload>, JsonRejection>,
) -> Result<Json<crate::dto::SftpScanDto>, ApiError> {
    validate_uuid_path(&endpoint_id, "endpoint_id")?;
    require_json(&headers, state.security.body_limit)?;
    let payload = parse_json_body(body)?;
    payload.validate()?;
    check_state_change(&state.security, &headers, &actor).await?;
    let permission = Permission::ChangePlan;
    state
        .management
        .authorize(&actor, "sftp-endpoints", Some(&endpoint_id), permission)
        .await?;
    let idempotency_key = required_header(&headers, "idempotency-key", 128)?;
    let if_match = required_header(&headers, "if-match", 256)?;
    if payload.endpoint_id != endpoint_id {
        return Err(ApiError::InvalidRequest("endpoint_id does not match route"));
    }
    let payload_hash = serde_json::to_vec(&payload)
        .map(|bytes| crate::plan_hash(&bytes))
        .map_err(|_| ApiError::InvalidRequest("sftp scan payload"))?;
    state
        .management
        .scan_sftp(
            &actor,
            &endpoint_id,
            payload,
            MutationContext {
                actor: actor.clone(),
                idempotency_key: idempotency_key.to_owned(),
                if_match: if_match.to_owned(),
                session_version: None,
                request_hash: payload_hash,
                expires_at: unix_now().saturating_add(24 * 60 * 60),
                request_id: request_id.0,
            },
        )
        .await
        .map(Json)
}

