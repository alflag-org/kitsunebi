fn resource_from_path(path: &str) -> Result<ResourceKind, ApiError> {
    let resource = path
        .split('/')
        .filter(|segment| !segment.is_empty())
        .nth(2)
        .ok_or(ApiError::NotFound)?;
    ResourceKind::parse(resource)
}

