fn require_json(headers: &HeaderMap, max_body_size: usize) -> Result<(), ApiError> {
    if headers.get_all(header::CONTENT_TYPE).iter().count() != 1 {
        return Err(ApiError::InvalidRequest(
            "application/json content type is required",
        ));
    }
    let value = headers
        .get(header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .ok_or(ApiError::InvalidRequest(
            "application/json content type is required",
        ))?;
    if value.split(';').next().map(str::trim) != Some("application/json") {
        Err(ApiError::InvalidRequest(
            "application/json content type is required",
        ))
    } else {
        if headers.get_all(header::CONTENT_LENGTH).iter().count() > 1 {
            return Err(ApiError::InvalidRequest("invalid content length"));
        }
        let length = headers
            .get(header::CONTENT_LENGTH)
            .map(|value| {
                value
                    .to_str()
                    .ok()
                    .and_then(|value| value.parse::<u64>().ok())
                    .ok_or(ApiError::InvalidRequest("invalid content length"))
            })
            .transpose()?;
        if length.is_some_and(|length| length > max_body_size as u64) {
            Err(ApiError::PayloadTooLarge)
        } else {
            Ok(())
        }
    }
}

fn parse_json_body<T>(body: Result<Json<T>, JsonRejection>) -> Result<T, ApiError> {
    body.map(|Json(value)| value).map_err(|rejection| {
        if rejection.status() == StatusCode::PAYLOAD_TOO_LARGE {
            ApiError::PayloadTooLarge
        } else if rejection
            .body_text()
            .contains("unsupported plan step action")
        {
            ApiError::Unsupported
        } else {
            ApiError::InvalidRequest("invalid JSON body")
        }
    })
}

fn validate_hex_hash(value: &str, field: &'static str) -> Result<(), ApiError> {
    if value.len() == 64 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        Ok(())
    } else {
        Err(ApiError::InvalidRequest(field))
    }
}

fn validate_request_hash_header(
    headers: &HeaderMap,
    body_request_hash: &str,
) -> Result<(), ApiError> {
    if headers.get_all("x-request-hash").iter().count() > 1 {
        return Err(ApiError::InvalidRequest("request hash header is invalid"));
    }
    let header_hash = headers
        .get("x-request-hash")
        .ok_or(ApiError::InvalidRequest("request hash header is required"))?;
    let header_hash = header_hash
        .to_str()
        .map_err(|_| ApiError::InvalidRequest("request hash header is invalid"))?;
    validate_hex_hash(header_hash, "request hash header")?;
    if header_hash != body_request_hash {
        return Err(ApiError::Conflict);
    }
    Ok(())
}

fn parse_session_version(value: &str) -> Result<u64, ApiError> {
    let value = value.trim();
    if value.len() < 3
        || !value.starts_with('"')
        || !value.ends_with('"')
        || value[1..value.len() - 1].contains('"')
        || value.contains(',')
    {
        return Err(ApiError::InvalidRequest("session version token is invalid"));
    }
    let version = value[1..value.len() - 1]
        .parse::<u64>()
        .map_err(|_| ApiError::InvalidRequest("session version token is invalid"))?;
    if version == 0 {
        return Err(ApiError::InvalidRequest("session version token is invalid"));
    }
    Ok(version)
}

