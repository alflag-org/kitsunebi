fn download_response(file: FileReadDto, limit: usize) -> Result<Response, ApiError> {
    if file.content.len() > limit {
        return Err(ApiError::PayloadTooLarge);
    }
    let disposition = safe_content_disposition(&file.path)?;
    let content_type = HeaderValue::from_str(validate_content_type(&file.content_type)?)
        .map_err(|_| ApiError::InvalidRequest("invalid content type"))?;
    let mut response = Response::new(Body::from(file.content));
    response
        .headers_mut()
        .insert(header::CONTENT_TYPE, content_type);
    response.headers_mut().insert(
        header::CONTENT_DISPOSITION,
        HeaderValue::from_str(&disposition)
            .map_err(|_| ApiError::InvalidRequest("unsafe filename"))?,
    );
    Ok(response)
}

