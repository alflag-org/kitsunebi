/// Correlation identifier generated by the API and passed to application audit ports.
#[derive(Clone, Debug)]
pub struct RequestId(pub String);

struct MutationDispatch<'a> {
    state: ApiState,
    actor: VerifiedActor,
    request_id: RequestId,
    resource: &'a str,
    id: Option<&'a str>,
    command: MutationCommand,
    action: MutationAction,
    headers: HeaderMap,
    body: Result<Json<MutationRequest>, JsonRejection>,
}

/// Shared route dependencies.
#[derive(Clone)]
pub struct ApiState {
    pub management: Arc<dyn ManagementApi>,
    pub authenticator: Arc<Authenticator>,
    pub security: Arc<SecurityConfig>,
    pub limiter: Arc<DangerRateLimiter>,
}
impl ApiState {
    pub fn new(
        management: Arc<dyn ManagementApi>,
        authenticator: Arc<Authenticator>,
        security: Arc<SecurityConfig>,
    ) -> Result<Self, ApiError> {
        security.validate()?;
        Ok(Self {
            management,
            authenticator,
            security,
            limiter: Arc::new(DangerRateLimiter::default()),
        })
    }
}

/// Build the public health endpoints and authenticated management API.
pub fn router(
    management: Arc<dyn ManagementApi>,
    authenticator: Arc<Authenticator>,
    security: Arc<SecurityConfig>,
) -> Result<Router, ApiError> {
    let state = ApiState::new(management, authenticator.clone(), security)?;
    let mut protected = Router::new();
    for resource in ResourceKind::ALL {
        let collection = format!("{API_PREFIX}/{}", resource.as_str());
        let item = format!("{collection}/{{id}}");
        if resource == ResourceKind::SftpEndpoints {
            protected = protected.route(&collection, axum::routing::get(list_sftp_endpoints));
            protected = protected.route(&item, axum::routing::get(get_sftp_endpoint));
            continue;
        }
        protected = protected.route(&collection, axum::routing::get(list));
        protected = protected.route(&item, axum::routing::get(get));
    }
    protected = protected
        .route(
            "/api/v1/change-sessions",
            axum::routing::post(begin_change_session),
        )
        .route(
            "/api/v1/change-sessions/{id}/plan",
            axum::routing::post(plan_change),
        )
        .route(
            "/api/v1/change-sessions/{id}/approve",
            axum::routing::post(approve_change),
        )
        .route(
            "/api/v1/change-sessions/{id}/apply",
            axum::routing::post(explicit_mutate),
        )
        .route(
            "/api/v1/change-sessions/{id}/verify",
            axum::routing::post(explicit_mutate),
        )
        .route(
            "/api/v1/change-sessions/{id}/accept",
            axum::routing::post(explicit_mutate),
        )
        .route(
            "/api/v1/change-sessions/{id}/rollback",
            axum::routing::post(explicit_mutate),
        )
        .route(
            "/api/v1/artifacts/discover",
            axum::routing::post(discover_artifacts),
        )
        .route(
            "/api/v1/sftp-endpoints/{id}/scan",
            axum::routing::post(scan_sftp),
        )
        .route(
            "/api/v1/operations/{id}/events",
            axum::routing::get(operation_events),
        )
        .route(
            "/api/v1/execution-units/{id}/console",
            axum::routing::get(console),
        )
        .route("/api/v1/session", axum::routing::post(session))
        .route(
            "/api/v1/health/providers",
            axum::routing::get(provider_health),
        );
    let file_routes = Router::new()
        .route(
            "/api/v1/execution-units/{id}/files",
            axum::routing::get(file_browse),
        )
        .route(
            "/api/v1/execution-units/{id}/files/browse",
            axum::routing::get(file_browse),
        )
        .route(
            "/api/v1/execution-units/{id}/files/read",
            axum::routing::get(file_read),
        )
        .route(
            "/api/v1/execution-units/{id}/files/download",
            axum::routing::get(file_download),
        )
        .route(
            "/api/v1/execution-units/{id}/files/diff",
            axum::routing::get(file_diff),
        )
        .layer(axum::extract::DefaultBodyLimit::max(
            state.security.body_limit,
        ));
    let staged_content_route = Router::new()
        .route(
            "/api/v1/change-sessions/{id}/staged-content",
            axum::routing::post(stage_content),
        )
        .layer(axum::extract::DefaultBodyLimit::max(
            state.security.upload_limit,
        ));
    let protected = protected
        .layer(axum::extract::DefaultBodyLimit::max(
            state.security.body_limit,
        ))
        .merge(file_routes)
        .merge(staged_content_route)
        .with_state(state.clone())
        .layer(middleware::from_fn_with_state(
            authenticator,
            auth::middleware,
        ));
    let public = Router::new()
        .route("/health", axum::routing::get(health))
        .route("/live", axum::routing::get(live))
        .route("/ready", axum::routing::get(ready))
        .route("/metrics", axum::routing::get(metrics))
        .with_state(state);
    Ok(public
        .merge(protected)
        .fallback(api_not_found)
        .layer(middleware::from_fn(request_id))
        .layer(middleware::from_fn(security_headers)))
}

async fn list(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    OriginalUri(uri): OriginalUri,
) -> Result<Json<Vec<ResourceDto>>, ApiError> {
    let resource = resource_from_path(uri.path())?;
    state
        .management
        .authorize(&actor, resource.as_str(), None, read_permission(resource))
        .await?;
    Ok(Json(
        state.management.list(resource.as_str(), &actor).await?,
    ))
}

async fn session(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    headers: HeaderMap,
) -> Result<Response, ApiError> {
    if actor.kind != crate::ports::ActorKind::Browser {
        return Err(ApiError::Forbidden);
    }
    check_origin(&state.security, &headers)?;
    state
        .limiter
        .check(
            &actor,
            state.security.dangerous_rate_limit,
            state.security.dangerous_rate_window,
        )
        .await?;
    let mut response = Json(SessionDto {
        csrf_token: state.security.csrf.issue(&actor)?,
    })
    .into_response();
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    Ok(response)
}

async fn begin_change_session(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Extension(request_id): Extension<RequestId>,
    headers: HeaderMap,
    body: Result<Json<ChangeBeginPayload>, JsonRejection>,
) -> Result<Json<ChangeSessionDto>, ApiError> {
    require_json(&headers, state.security.body_limit)?;
    check_state_change(&state.security, &headers, &actor).await?;
    let idempotency_key = required_header(&headers, "idempotency-key", 128)?;
    let payload = parse_json_body(body)?;
    validate_uuid_path(&payload.service_id, "service_id")?;
    validate_uuid_path(&payload.cluster_id, "cluster_id")?;
    state
        .management
        .begin_change_session(&actor, payload, idempotency_key, &request_id.0)
        .await
        .map(Json)
}
