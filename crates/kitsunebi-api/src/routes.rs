/// Action routes use the mutation envelope, but bind a closed operation name
/// to a concrete resource and object path.
async fn explicit_mutate(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Extension(request_id): Extension<RequestId>,
    OriginalUri(uri): OriginalUri,
    Path(id): Path<String>,
    headers: HeaderMap,
    body: Result<Json<MutationRequest>, JsonRejection>,
) -> Result<Json<OperationDto>, ApiError> {
    validate_uuid_path(&id, "change_session_id")?;
    let action_name = uri_action_name(uri.path());
    let command = match action_name {
        "apply" => MutationCommand::Apply,
        "verify" => MutationCommand::Verify,
        "accept" => MutationCommand::Accept,
        "rollback" => MutationCommand::Rollback,
        _ => return Err(ApiError::NotFound),
    };
    dispatch_mutation(MutationDispatch {
        state,
        actor,
        request_id,
        resource: "change-sessions",
        id: Some(&id),
        command,
        action: MutationAction::Change,
        headers,
        body,
    })
    .await
}

fn uri_action_name(path: &str) -> &str {
    path.rsplit('/')
        .find(|segment| !segment.is_empty())
        .unwrap_or("")
}

async fn plan_change(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Extension(request_id): Extension<RequestId>,
    Path(id): Path<String>,
    headers: HeaderMap,
    body: Result<Json<MutationRequest>, JsonRejection>,
) -> Result<Json<crate::dto::ChangePlanResultDto>, ApiError> {
    validate_uuid_path(&id, "change_session_id")?;
    let resource = "change-sessions";
    require_json(&headers, state.security.body_limit)?;
    let request = parse_json_body(body)?;
    request.validate_for(resource, MutationCommand::Plan, MutationAction::Change)?;
    validate_request_hash_header(&headers, &request.request_hash)?;
    check_state_change(&state.security, &headers, &actor).await?;
    state
        .management
        .authorize(&actor, resource, Some(&id), Permission::ChangePlan)
        .await?;
    let idem = required_header(&headers, "idempotency-key", 128)?;
    let if_match = required_header(&headers, "if-match", 256)?;
    let now = unix_now();
    if request.expires_at <= now || request.expires_at > now.saturating_add(24 * 60 * 60) {
        return Err(ApiError::InvalidRequest(
            "plan expiry is outside the allowed window",
        ));
    }
    state
        .management
        .plan_change(
            &actor,
            resource,
            &id,
            request.clone(),
            MutationContext {
                actor: actor.clone(),
                idempotency_key: idem.to_owned(),
                if_match: if_match.to_owned(),
                session_version: Some(parse_session_version(if_match)?),
                request_hash: request.request_hash,
                expires_at: request.expires_at,
                request_id: request_id.0,
            },
        )
        .await
        .map(Json)
}

