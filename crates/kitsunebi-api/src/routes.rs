async fn dispatch_mutation(dispatch: MutationDispatch<'_>) -> Result<Json<OperationDto>, ApiError> {
    let MutationDispatch {
        state,
        actor,
        request_id,
        resource,
        id,
        command,
        action,
        headers,
        body,
    } = dispatch;
    let body_limit = state.security.body_limit;
    require_json(&headers, body_limit)?;
    let request = parse_json_body(body)?;
    request.validate_for(resource, command, action)?;
    validate_request_hash_header(&headers, &request.request_hash)?;
    check_state_change(&state.security, &headers, &actor).await?;
    let permission = permission_for(resource, action, command);
    state
        .management
        .authorize(&actor, resource, id, permission)
        .await?;
    if dangerous_mutation(action, command) {
        state
            .limiter
            .check(
                &actor,
                state.security.dangerous_rate_limit,
                state.security.dangerous_rate_window,
            )
            .await?;
    }
    let idem = required_header(&headers, "idempotency-key", 128)?;
    let if_match = required_header(&headers, "if-match", 256)?;
    let now = unix_now();
    if request.expires_at <= now || request.expires_at > now.saturating_add(24 * 60 * 60) {
        return Err(ApiError::InvalidRequest(
            "plan expiry is outside the allowed window",
        ));
    }
    let operation = state
        .management
        .mutate(
            resource,
            id,
            request.clone(),
            MutationContext {
                actor,
                idempotency_key: idem.to_owned(),
                if_match: if_match.to_owned(),
                session_version: None,
                request_hash: request.request_hash,
                expires_at: request.expires_at,
                request_id: request_id.0,
            },
        )
        .await?;
    Ok(Json(operation))
}

fn read_permission(resource: ResourceKind) -> Permission {
    match resource {
        ResourceKind::Artifacts => Permission::ArtifactDiscover,
        ResourceKind::Worlds => Permission::WorldRead,
        ResourceKind::Endpoints => Permission::EndpointRead,
        ResourceKind::AccessPolicies => Permission::AccessRead,
        ResourceKind::AuditEvents => Permission::AuditRead,
        ResourceKind::Operations => Permission::OperationRead,
        _ => Permission::ServiceRead,
    }
}

fn permission_for(resource: &str, action: MutationAction, command: MutationCommand) -> Permission {
    match action {
        MutationAction::Change => match resource {
            "worlds" => Permission::WorldWrite,
            "endpoints" => Permission::EndpointWrite,
            "access-policies" => Permission::AccessManage,
            _ => match command {
                MutationCommand::Plan => Permission::ChangePlan,
                MutationCommand::Approve => Permission::ChangeApprove,
                MutationCommand::Apply => Permission::ChangeApply,
                MutationCommand::Verify => Permission::ChangeVerify,
                MutationCommand::Accept => Permission::ChangeAccept,
                MutationCommand::Rollback => Permission::ChangeRollback,
            },
        },
    }
}
fn dangerous_mutation(action: MutationAction, command: MutationCommand) -> bool {
    !matches!(
        (action, command),
        (MutationAction::Change, MutationCommand::Plan)
            | (MutationAction::Change, MutationCommand::Verify)
    )
}

async fn operation_events(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Path(id): Path<String>,
) -> Result<Sse<impl Stream<Item = Result<Event, Infallible>>>, ApiError> {
    state
        .management
        .authorize(&actor, "operations", Some(&id), Permission::OperationRead)
        .await?;
    let mut stream = state.management.open_operation_stream(&actor, &id).await?;
    let deadline = Instant::now() + SSE_LIFETIME;
    let output = async_stream::stream! {
        loop {
            tokio::select! {
                _ = time::sleep_until(deadline) => break,
                event = time::timeout(SSE_IDLE, stream.next()) => {
                    match event {
                        Ok(Ok(Some(event))) => yield Ok(event_to_sse(event)),
                        Ok(Ok(None)) | Ok(Err(_)) | Err(_) => break,
                    }
                }
            }
        }
    };
    Ok(Sse::new(output).keep_alive(KeepAlive::default()))
}
fn event_to_sse(event: OperationEvent) -> Event {
    Event::default()
        .event("operation")
        .json_data(event)
        .unwrap_or_else(|_| Event::default().event("operation"))
}

async fn console(
    State(state): State<ApiState>,
    Extension(actor): Extension<VerifiedActor>,
    Path(id): Path<String>,
    headers: HeaderMap,
    upgrade: WebSocketUpgrade,
) -> Result<Response, ApiError> {
    state
        .management
        .authorize(
            &actor,
            "execution-units",
            Some(&id),
            Permission::ConsoleRead,
        )
        .await?;
    let can_command = match state
        .management
        .authorize(
            &actor,
            "execution-units",
            Some(&id),
            Permission::ConsoleSend,
        )
        .await
    {
        Ok(_) => true,
        // A read-only console is a supported session. Other authorization
        // failures (for example a storage outage) must not be hidden as a
        // missing command grant.
        Err(ApiError::Forbidden | ApiError::NotFound) => false,
        Err(error) => return Err(error),
    };
    if actor.kind == crate::ports::ActorKind::Browser {
        check_origin(&state.security, &headers)?;
        if headers.contains_key("x-csrf-token") {
            return Err(ApiError::Forbidden);
        }
    }
    if can_command {
        if actor.kind == crate::ports::ActorKind::Browser {
            verify_console_protocol(&headers, &state.security, &actor)?;
        } else {
            // Service actors use the explicit originless path.
            check_state_change(&state.security, &headers, &actor).await?;
        }
    } else if !has_console_base_protocol(&headers)? {
        return Err(ApiError::Forbidden);
    }
    let session = state.management.open_console(&actor, &id).await?;
    let limiter = state.limiter.clone();
    let actor_for_relay = actor.clone();
    let rate_limit = state.security.dangerous_rate_limit;
    let rate_window = state.security.dangerous_rate_window;
    Ok(upgrade
        .protocols(["kitsunebi.v1"])
        .max_write_buffer_size(CONSOLE_FRAME_LIMIT * 2)
        .max_message_size(CONSOLE_FRAME_LIMIT)
        .max_frame_size(CONSOLE_FRAME_LIMIT)
        .on_upgrade(move |socket| {
            console_relay(
                socket,
                session,
                can_command,
                limiter,
                actor_for_relay,
                rate_limit,
                rate_window,
            )
        }))
}

fn has_console_base_protocol(headers: &HeaderMap) -> Result<bool, ApiError> {
    let mut has_base = false;
    let mut has_csrf = false;
    for value in headers.get_all("sec-websocket-protocol") {
        let value = value.to_str().map_err(|_| ApiError::Forbidden)?;
        for protocol in value.split(',') {
            let protocol = protocol.trim();
            if protocol == "kitsunebi.v1" {
                if has_base {
                    return Err(ApiError::Forbidden);
                }
                has_base = true;
            } else if protocol.strip_prefix("csrf.").is_some() {
                if has_csrf {
                    return Err(ApiError::Forbidden);
                }
                has_csrf = true;
            } else {
                return Err(ApiError::Forbidden);
            }
        }
    }
    Ok(has_base)
}

fn verify_console_protocol(
    headers: &HeaderMap,
    security: &SecurityConfig,
    actor: &VerifiedActor,
) -> Result<(), ApiError> {
    let mut has_base = false;
    let mut csrf = None;
    for value in headers.get_all("sec-websocket-protocol") {
        let value = value.to_str().map_err(|_| ApiError::Forbidden)?;
        for protocol in value.split(',').map(str::trim) {
            if protocol.is_empty() {
                return Err(ApiError::Forbidden);
            }
            if protocol == "kitsunebi.v1" {
                if has_base {
                    return Err(ApiError::Forbidden);
                }
                has_base = true;
            } else if let Some(token) = protocol.strip_prefix("csrf.") {
                if csrf.replace(token).is_some() {
                    return Err(ApiError::Forbidden);
                }
            } else {
                return Err(ApiError::Forbidden);
            }
        }
    }
    let token = csrf.ok_or(ApiError::Forbidden)?;
    if !has_base || !security.csrf.verify(actor, token) {
        return Err(ApiError::Forbidden);
    }
    Ok(())
}
async fn console_relay(
    mut socket: WebSocket,
    mut session: Box<dyn ConsoleSession>,
    can_command: bool,
    limiter: Arc<DangerRateLimiter>,
    actor: VerifiedActor,
    rate_limit: usize,
    rate_window: Duration,
) {
    let end = Instant::now() + CONSOLE_LIFETIME;
    loop {
        tokio::select! {
            _ = time::sleep_until(end) => break,
            inbound = time::timeout(CONSOLE_IDLE, socket.recv()) => {
                let message = match inbound {
                    Ok(Some(Ok(message))) => message,
                    _ => break,
                };
                let frame = match message {
                    Message::Text(text) => {
                        if !can_command || text.len() > CONSOLE_FRAME_LIMIT {
                            break;
                        }
                        if limiter.check(&actor, rate_limit, rate_window).await.is_err() {
                            break;
                        }
                        ConsoleFrame::Text(text.to_string())
                    }
                    Message::Binary(bytes) => {
                        if !can_command || bytes.len() > CONSOLE_FRAME_LIMIT {
                            break;
                        }
                        if limiter.check(&actor, rate_limit, rate_window).await.is_err() {
                            break;
                        }
                        ConsoleFrame::Binary(bytes.to_vec())
                    }
                    Message::Ping(_) | Message::Pong(_) => continue,
                    Message::Close(_) => break,
                };
                if session
                    .record(audit_event(&frame, ConsoleDirection::ClientToBackend))
                    .await
                    .is_err()
                {
                    break;
                }
                if !matches!(
                    time::timeout(CONSOLE_IO_TIMEOUT, session.send(frame)).await,
                    Ok(Ok(()))
                ) {
                    break;
                }
            }
            backend = time::timeout(CONSOLE_IDLE, session.receive()) => {
                match backend {
                    Ok(Ok(Some(ConsoleFrame::Text(text)))) => {
                        let event = ConsoleAuditEvent {
                            direction: ConsoleDirection::BackendToClient,
                            size: text.len(),
                            digest: crate::plan_hash(text.as_bytes()),
                        };
                        if session.record(event).await.is_err() {
                            break;
                        }
                        if text.len() > CONSOLE_FRAME_LIMIT
                            || !matches!(
                                time::timeout(
                                    CONSOLE_IO_TIMEOUT,
                                    socket.send(Message::Text(text.into()))
                                )
                                .await,
                                Ok(Ok(()))
                            )
                        {
                            break;
                        }
                    }
                    Ok(Ok(Some(ConsoleFrame::Binary(bytes)))) => {
                        let event = ConsoleAuditEvent {
                            direction: ConsoleDirection::BackendToClient,
                            size: bytes.len(),
                            digest: crate::plan_hash(&bytes),
                        };
                        if session.record(event).await.is_err() {
                            break;
                        }
                        if bytes.len() > CONSOLE_FRAME_LIMIT
                            || !matches!(
                                time::timeout(
                                    CONSOLE_IO_TIMEOUT,
                                    socket.send(Message::Binary(bytes.into()))
                                )
                                .await,
                                Ok(Ok(()))
                            )
                        {
                            break;
                        }
                    }
                    Ok(Ok(None)) | Ok(Err(_)) | Err(_) => break,
                }
            }
        }
    }
    let _ = time::timeout(CONSOLE_CLOSE_TIMEOUT, socket.send(Message::Close(None))).await;
    let _ = time::timeout(CONSOLE_CLOSE_TIMEOUT, session.close()).await;
}
fn audit_event(frame: &ConsoleFrame, direction: ConsoleDirection) -> ConsoleAuditEvent {
    match frame {
        ConsoleFrame::Text(text) => ConsoleAuditEvent {
            direction,
            size: text.len(),
            digest: crate::plan_hash(text.as_bytes()),
        },
        ConsoleFrame::Binary(bytes) => ConsoleAuditEvent {
            direction,
            size: bytes.len(),
            digest: crate::plan_hash(bytes),
        },
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct FilePathQuery {
    path: Option<String>,
}
fn parse_file_query(
    query: Result<Query<FilePathQuery>, QueryRejection>,
) -> Result<FilePathQuery, ApiError> {
    query
        .map(|Query(query)| query)
        .map_err(|_| ApiError::InvalidRequest("invalid file query"))
}
fn query_path(query: &FilePathQuery) -> Result<String, ApiError> {
    match query.path.as_deref() {
        None | Some("") => Ok(".".to_owned()),
        Some(".") => Ok(".".to_owned()),
        Some(path) => validate_relative_path(path),
    }
}
fn validate_uuid_path(value: &str, field: &'static str) -> Result<(), ApiError> {
    if Uuid::parse_str(value).is_err() {
        return Err(ApiError::InvalidRequest(field));
    }
    Ok(())
}
